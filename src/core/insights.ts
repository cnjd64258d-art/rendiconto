import { inPeriod, monthKey, totalsOf, type Basis } from './analysis';
import { addDays, addMonths, isoWeekday, monthOf, yearOf, type ISODate, type YearMonth } from './dates';
import { formatCents, formatMonth, formatPercent } from './format';
import type { Cents } from './money';
import { kindResolver, yearlyCents } from './recurring';
import { cleanTitle, effectiveCents, normalizeText } from './transactions';
import type { Category, CategoryGroup, Id, RecurringRule, Transaction } from './types';

export interface Insight {
  id: string;
  emoji: string;
  text: string;
  tone: 'neutral' | 'positive' | 'warning';
}

export interface InsightInput {
  transactions: readonly Transaction[];
  rules: readonly RecurringRule[];
  categories: readonly Category[];
  groups: readonly CategoryGroup[];
  basis: Basis;
  /** The month the analysis looks at (end of the selected period). */
  month: YearMonth;
  today: ISODate;
}

/** Thresholds of the "spesa sopra/sotto la media" rule. */
export const SPIKE_RATIO = 0.25;
export const SPIKE_MIN_CENTS = 3000;
const HISTORY_MONTHS = 6;
const MERCHANT_MIN_COUNT = 4;
const WEEKDAY_DAYS = 84;
const WEEKDAYS = ['lunedì', 'martedì', 'mercoledì', 'giovedì', 'venerdì', 'sabato', 'domenica'];

/** Plain-language insights from local, deterministic rules. Most relevant first. */
export function insights(input: InsightInput): Insight[] {
  return [...categorySpikes(input), ...savingsPace(input), ...topMerchant(input), ...subscriptions(input), ...busiestWeekday(input)];
}

const MONTH_NAME = (m: YearMonth) => formatMonth(m, false);
/** Above this average, a repeated expense is not an "everyday" one (rent, mortgage…). */
const MERCHANT_MAX_AVG_CENTS = 15000;

/**
 * Fixed costs say nothing about habits: rows generated by a recurring rule, instalments, and rows whose
 * description matches a recurring rule (imported history has no link to the rule).
 */
function fixedCostFilter(rules: readonly RecurringRule[]): (t: Transaction) => boolean {
  const titles = new Set(rules.map((r) => normalizeText(r.title)));
  return (t) => t.recurringRuleId !== undefined || t.installmentPlanId !== undefined || titles.has(normalizeText(t.title));
}

/** "A ottobre hai speso il 34% in più in Cibo rispetto alla tua media". Compares a complete month only. */
export function categorySpikes({ transactions, rules, categories, basis, month, today }: InsightInput): Insight[] {
  const isFixed = fixedCostFilter(rules);
  // A month in progress would always look "below average": use the last complete one.
  const target = month >= monthOf(today) ? addMonths(monthOf(today), -1) : month;
  const from = addMonths(target, -HISTORY_MONTHS);
  const spend = new Map<Id, Map<YearMonth, Cents>>();
  const monthsWithData = new Set<YearMonth>();
  for (const t of transactions) {
    if (t.kind !== 'expense' || t.status !== 'confirmed' || !t.categoryId || isFixed(t)) continue;
    const m = monthKey(t, basis);
    if (m < from || m > target) continue;
    if (m < target) monthsWithData.add(m);
    let byMonth = spend.get(t.categoryId);
    if (!byMonth) spend.set(t.categoryId, (byMonth = new Map()));
    byMonth.set(m, (byMonth.get(m) ?? 0) + effectiveCents(t));
  }
  // Enough history to talk about "your average".
  if (monthsWithData.size < 3) return [];
  const catById = new Map(categories.map((c) => [c.id, c]));
  const found: (Insight & { weight: number })[] = [];
  for (const [categoryId, byMonth] of spend) {
    const current = byMonth.get(target) ?? 0;
    // Irregular categories (quarterly bills, one-off trips) would always look like a spike.
    const present = [...monthsWithData].filter((m) => (byMonth.get(m) ?? 0) > 0).length;
    if (current === 0 || present * 2 < monthsWithData.size) continue;
    let sum = 0;
    for (const m of monthsWithData) sum += byMonth.get(m) ?? 0;
    const avg = sum / monthsWithData.size;
    if (avg <= 0) continue;
    const diff = current - avg;
    const ratio = diff / avg;
    if (Math.abs(diff) < SPIKE_MIN_CENTS || Math.abs(ratio) < SPIKE_RATIO) continue;
    const name = catById.get(categoryId)?.name ?? 'una categoria';
    const more = diff > 0;
    found.push({
      id: `spike:${categoryId}:${target}`,
      emoji: more ? '📈' : '📉',
      tone: more ? 'warning' : 'positive',
      text: `A ${MONTH_NAME(target)} hai speso il ${formatPercent(Math.abs(ratio))} in ${more ? 'più' : 'meno'} in ${name} rispetto alla tua media (${formatCents(current, { decimals: false })} contro ${formatCents(Math.round(avg), { decimals: false })} al mese).`,
      weight: Math.abs(diff),
    });
  }
  return found
    .sort((a, b) => b.weight - a.weight)
    .slice(0, 2)
    .map((i): Insight => ({ id: i.id, emoji: i.emoji, tone: i.tone, text: i.text }));
}

/** "Il car sharing ti è costato 412 € quest'anno": the everyday expense (same description) that cost most this year. */
export function topMerchant({ transactions, rules, basis, month, today }: InsightInput): Insight[] {
  const isFixed = fixedCostFilter(rules);
  const year = yearOf(month);
  const rows = inPeriod(transactions, { from: `${year}-01`, to: `${year}-12` }, basis);
  const byTitle = new Map<string, { title: string; cents: Cents; count: number }>();
  for (const t of rows) {
    if (t.kind !== 'expense' || isFixed(t)) continue;
    const key = normalizeText(t.title);
    const cur = byTitle.get(key) ?? { title: cleanTitle(t.title), cents: 0, count: 0 };
    cur.cents += effectiveCents(t);
    cur.count += 1;
    byTitle.set(key, cur);
  }
  let best: { title: string; cents: Cents; count: number } | undefined;
  for (const v of byTitle.values()) {
    if (v.count < MERCHANT_MIN_COUNT || v.cents / v.count > MERCHANT_MAX_AVG_CENTS) continue;
    if (!best || v.cents > best.cents) best = v;
  }
  if (!best) return [];
  const when = year === yearOf(today) ? "quest'anno" : `nel ${year}`;
  return [
    {
      id: `merchant:${year}`,
      emoji: '🔎',
      tone: 'neutral',
      text: `${best.title} ti è costato ${formatCents(best.cents, { decimals: false })} ${when} (${best.count} volte, ${formatCents(Math.round(best.cents / best.count))} in media).`,
    },
  ];
}

/** "Abbonamenti attivi: 6, per un totale di 1.090 €/anno" (active recurring expenses of the Abbonamenti macro-voce). */
export function subscriptions({ rules, categories, groups }: InsightInput): Insight[] {
  const kindOf = kindResolver(categories, groups);
  const groupOf = new Map(categories.map((c) => [c.id, c.groupId]));
  const active = rules.filter((r) => r.active && kindOf(r.categoryId) === 'expense');
  if (active.length === 0) return [];
  const subs = active.filter((r) => groupOf.get(r.categoryId) === 'grp_abbonamenti');
  const out: Insight[] = [];
  if (subs.length > 0) {
    const yearly = subs.reduce((s, r) => s + yearlyCents(r), 0);
    out.push({
      id: 'subscriptions',
      emoji: '🔁',
      tone: 'neutral',
      text: `Abbonamenti attivi: ${subs.length}, per un totale di ${formatCents(yearly, { decimals: false })}/anno.`,
    });
  }
  const fixed = active.reduce((s, r) => s + yearlyCents(r), 0);
  out.push({
    id: 'fixed',
    emoji: '📌',
    tone: 'neutral',
    text: `Spese fisse attive: ${active.length}, circa ${formatCents(Math.round(fixed / 12), { decimals: false })} al mese (${formatCents(fixed, { decimals: false })}/anno).`,
  });
  return out;
}

/** Savings rate from January to the reference month, against the same months of the year before. */
export function savingsPace({ transactions, basis, month }: InsightInput): Insight[] {
  const year = yearOf(month);
  const mm = month.slice(5, 7);
  const now = totalsOf(inPeriod(transactions, { from: `${year}-01`, to: month }, basis));
  if (now.savingsRate === null) return [];
  const before = totalsOf(inPeriod(transactions, { from: `${year - 1}-01`, to: `${year - 1}-${mm}` }, basis));
  const span = mm === '01' ? `A ${MONTH_NAME(month)}` : mm === '12' ? `Nel ${year}` : `Da gennaio a ${MONTH_NAME(month)}`;
  const rate = now.savingsRate;
  const amount = formatCents(Math.abs(now.savingsCents), { decimals: false });
  const text =
    now.savingsCents >= 0
      ? `${span} hai risparmiato ${amount}, il ${formatPercent(rate)} delle entrate`
      : `${span} hai speso ${amount} più delle entrate`;
  if (before.savingsRate === null) return [{ id: `pace:${month}`, emoji: rate >= 0 ? '🐷' : '⚠️', tone: rate >= 0 ? 'positive' : 'warning', text: `${text}.` }];
  const better = rate >= before.savingsRate;
  return [
    {
      id: `pace:${month}`,
      emoji: better ? '🐷' : '⚠️',
      tone: better ? 'positive' : 'warning',
      text: `${text} (stesso periodo del ${year - 1}: ${formatPercent(before.savingsRate)}).`,
    },
  ];
}

/** "Il sabato spendi di più": everyday expenses by weekday over the last 12 weeks, by payment date. */
export function busiestWeekday({ transactions, rules, today }: InsightInput): Insight[] {
  const isFixed = fixedCostFilter(rules);
  const from = addDays(today, -(WEEKDAY_DAYS - 1));
  const sums = [0, 0, 0, 0, 0, 0, 0];
  let any = 0;
  for (const t of transactions) {
    if (t.kind !== 'expense' || t.status !== 'confirmed' || isFixed(t)) continue;
    if (t.date < from || t.date > today) continue;
    const i = isoWeekday(t.date) - 1;
    sums[i] = (sums[i] ?? 0) + effectiveCents(t);
    any += 1;
  }
  if (any < 20) return [];
  // 12 weeks: every weekday occurs 12 times.
  const weeks = WEEKDAY_DAYS / 7;
  const avgs = sums.map((s) => s / weeks);
  let top = 0;
  avgs.forEach((a, i) => {
    if (a > (avgs[top] ?? 0)) top = i;
  });
  const others = (avgs.reduce((s, a) => s + a, 0) - (avgs[top] ?? 0)) / 6;
  if (others <= 0 || (avgs[top] ?? 0) < others * 1.5) return [];
  return [
    {
      id: 'weekday',
      emoji: '🗓️',
      tone: 'neutral',
      text: `${top === 6 ? 'La' : 'Il'} ${WEEKDAYS[top]} è il giorno in cui spendi di più: in media ${formatCents(Math.round(avgs[top] ?? 0), { decimals: false })}, contro ${formatCents(Math.round(others), { decimals: false })} degli altri giorni (ultime 12 settimane, spese fisse escluse).`,
    },
  ];
}
